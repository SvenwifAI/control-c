// MARK: - Model

struct ClipItem: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String?
    var imageFile: String?
    var imageHash: String?
    var date = Date()
    var appBundleID: String?
    var appName: String?

    var isImage: Bool { imageFile != nil }

    var isLink: Bool {
        guard let t = text?.trimmingCharacters(in: .whitespacesAndNewlines),
              !t.contains(where: \.isWhitespace),
              let scheme = URL(string: t)?.scheme?.lowercased() else { return false }
        return scheme == "http" || scheme == "https"
    }

    var oneLine: String {
        guard let text else { return "Afbeelding" }
        let collapsed = text.prefix(300).split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return collapsed.isEmpty ? "(witruimte)" : collapsed
    }
}

final class ClipStore: ObservableObject {
    static let maxItems = 60
    static let maxAge: TimeInterval = 7 * 24 * 3600
    static let maxTextBytes = 1_000_000
    static let maxImageBytes = 20_000_000

    @Published private(set) var items: [ClipItem] = []
    let dir: URL
    private var lastChange = -1
    private var timer: Timer?
    private let imageCache = NSCache<NSString, NSImage>()
    private var iconCache: [String: NSImage] = [:]

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    init() {
        dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ControlC", isDirectory: true)
        // Owner-only, and kept out of Time Machine: the history can contain anything you copied.
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        try? FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: dir.path)
        var values = URLResourceValues()
        values.isExcludedFromBackup = true
        var excluded = dir
        try? excluded.setResourceValues(values)
        load()
        expireOldItems()
    }

    private var historyURL: URL { dir.appendingPathComponent("history.json") }

    func start() {
        poll()
        let t = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
        expiryTimer = Timer.scheduledTimer(withTimeInterval: 600, repeats: true) { [weak self] _ in
            self?.expireOldItems()
        }
    }

    private var expiryTimer: Timer?

    /// Drops items not copied or used for `maxAge`, including their image files.
    func expireOldItems() {
        let cutoff = Date().addingTimeInterval(-Self.maxAge)
        let expired = items.filter { $0.date < cutoff }
        guard !expired.isEmpty else { return }
        items.removeAll { $0.date < cutoff }
        expired.forEach(removeFile(of:))
        save()
    }

    /// Only files this app wrote itself ("<24 hex chars>.png"); rejects anything else, such as
    /// a tampered history.json pointing at "../../somewhere".
    private func fileURL(_ name: String?) -> URL? {
        guard let name, name.count == 28, name.hasSuffix(".png"),
              name.dropLast(4).allSatisfy({ $0.isHexDigit }) else { return nil }
        return dir.appendingPathComponent(name)
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        // Password managers mark secrets as concealed; never store those.
        if let types = pb.types, types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard s.utf8.count <= Self.maxTextBytes else { return }
            if let i = items.firstIndex(where: { $0.text == s }) { promote(at: i); return }
            insert(ClipItem(text: s, appBundleID: app?.bundleIdentifier, appName: app?.localizedName))
        } else if let img = NSImage(pasteboard: pb), let png = img.pngData, png.count <= Self.maxImageBytes {
            let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            if let i = items.firstIndex(where: { $0.imageHash == hash }) { promote(at: i); return }
            let name = "\(hash.prefix(24)).png"
            guard let url = fileURL(name), (try? png.write(to: url)) != nil else { return }
            insert(ClipItem(imageFile: name, imageHash: hash, appBundleID: app?.bundleIdentifier, appName: app?.localizedName))
        }
    }

    private func insert(_ item: ClipItem) {
        items.insert(item, at: 0)
        while items.count > Self.maxItems { removeFile(of: items.removeLast()) }
        save()
    }

    private func promote(at i: Int) {
        guard i > 0 else { return }
        var item = items.remove(at: i)
        item.date = Date()
        items.insert(item, at: 0)
        save()
    }

    func copyToPasteboard(_ item: ClipItem, promote shouldPromote: Bool = true) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let t = item.text {
            pb.setString(t, forType: .string)
        } else if let img = image(for: item) {
            pb.writeObjects([img])
        }
        lastChange = pb.changeCount
        if shouldPromote, let i = items.firstIndex(where: { $0.id == item.id }) { promote(at: i) }
    }

    /// The most recent deletion, kept (image file included) until it is undone or finalized.
    @Published private(set) var lastDeleted: (item: ClipItem, index: Int)?

    func delete(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        finalizeDelete()
        items.remove(at: i)
        lastDeleted = (item, i)
        save()
    }

    func undoDelete() {
        guard let (item, index) = lastDeleted else { return }
        lastDeleted = nil
        items.insert(item, at: min(index, items.count))
        save()
    }

    func finalizeDelete() {
        guard let (item, _) = lastDeleted else { return }
        lastDeleted = nil
        removeFile(of: item)
    }

    func clear() {
        finalizeDelete()
        let removed = items
        items.removeAll()
        removed.forEach(removeFile(of:))
        save()
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let f = item.imageFile, let url = fileURL(f) else { return nil }
        if let cached = imageCache.object(forKey: f as NSString) { return cached }
        guard let img = NSImage(contentsOf: url) else { return nil }
        imageCache.setObject(img, forKey: f as NSString)
        return img
    }

    func appIcon(for item: ClipItem) -> NSImage? {
        guard let id = item.appBundleID else { return nil }
        if let cached = iconCache[id] { return cached }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: id) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        iconCache[id] = icon
        return icon
    }

    private func removeFile(of item: ClipItem) {
        guard let f = item.imageFile, let url = fileURL(f), !items.contains(where: { $0.imageFile == f }) else { return }
        try? FileManager.default.removeItem(at: url)
        imageCache.removeObject(forKey: f as NSString)
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }
}

extension NSImage {
    var pngData: Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}

// MARK: - Picker state

final class PickerModel: ObservableObject {
    @Published var query = "" { didSet { selection = 0 } }
    @Published var selection = 0
    @Published var focusToken = 0
    @Published var copiedID: UUID?
    @Published var expanded = UserDefaults.standard.bool(forKey: "expanded") {
        didSet {
            UserDefaults.standard.set(expanded, forKey: "expanded")
            onResize()
        }
    }
    let store: ClipStore
    var onChoose: (ClipItem, Bool) -> Void = { _, _ in }
    var onResize: () -> Void = {}

    init(store: ClipStore) { self.store = store }

    var filtered: [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return store.items }
        return store.items.filter {
            ($0.text ?? "afbeelding image").localizedCaseInsensitiveContains(q)
                || ($0.appName ?? "").localizedCaseInsensitiveContains(q)
        }
    }

    var selected: ClipItem? {
        let f = filtered
        return f.indices.contains(selection) ? f[selection] : nil
    }

    func move(_ delta: Int) {
        let count = filtered.count
        guard count > 0 else { return }
        selection = max(0, min(count - 1, selection + delta))
    }

    func clampSelection() {
        selection = max(0, min(filtered.count - 1, selection))
    }

    @Published var confirmingClear = false

    /// Deletes with a short undo window; the image file is only removed once that window closes.
    func delete(_ item: ClipItem) {
        confirmingClear = false
        store.delete(item)
        clampSelection()
        DispatchQueue.main.asyncAfter(deadline: .now() + 6) { [weak self] in
            if self?.store.lastDeleted?.item.id == item.id { self?.store.finalizeDelete() }
        }
    }

    func undoDelete() {
        guard let item = store.lastDeleted?.item else { return }
        store.undoDelete()
        if let i = filtered.firstIndex(where: { $0.id == item.id }) { selection = i }
    }

    func clearAll() {
        store.clear()
        confirmingClear = false
        selection = 0
    }
}

// MARK: - Views

struct VisualEffect: NSViewRepresentable {
    var material: NSVisualEffectView.Material = .popover

    func makeNSView(context: Context) -> NSVisualEffectView {
        let v = NSVisualEffectView()
        v.material = material
        v.blendingMode = .behindWindow
        v.state = .active
        return v
    }

    func updateNSView(_ v: NSVisualEffectView, context: Context) {}
}

func relativeTime(_ date: Date) -> String {
    let s = Int(-date.timeIntervalSinceNow)
    switch s {
    case ..<60: return "zojuist"
    case ..<3600: return "\(s / 60) min geleden"
    case ..<86400: return "\(s / 3600) uur geleden"
    case ..<172_800: return "gisteren"
    default: return "\(s / 86400) dagen geleden"
    }
}

struct PickerView: View {
    @ObservedObject var model: PickerModel
    @ObservedObject var store: ClipStore
    @FocusState private var searchFocused: Bool
    @State private var hoveredID: UUID?

    static let cornerRadius: CGFloat = 14

    var body: some View {
        let items = model.filtered
        VStack(spacing: 0) {
            searchBar
            Divider().opacity(0.5)
            if items.isEmpty {
                emptyState
            } else if model.expanded {
                HStack(spacing: 0) {
                    list(items).frame(width: 320)
                    Divider().opacity(0.5)
                    PreviewPane(item: model.selected, store: store)
                }
            } else {
                list(items)
            }
            if model.expanded {
                Divider().opacity(0.5)
                footer
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
        .overlay(alignment: .bottom) { banner.padding(.bottom, model.expanded ? 40 : 6) }
        .animation(.easeOut(duration: 0.15), value: store.lastDeleted?.item.id)
        .animation(.easeOut(duration: 0.15), value: model.confirmingClear)
        .background(VisualEffect(material: .menu))
        .clipShape(RoundedRectangle(cornerRadius: Self.cornerRadius, style: .continuous))
        .overlay(
            RoundedRectangle(cornerRadius: Self.cornerRadius, style: .continuous)
                .strokeBorder(Color.primary.opacity(0.1), lineWidth: 0.5)
        )
        .onAppear { searchFocused = true }
        .onChange(of: model.focusToken) { searchFocused = true }
    }

    private var searchBar: some View {
        HStack(spacing: 8) {
            Image(systemName: "magnifyingglass")
                .font(.system(size: model.expanded ? 15 : 13, weight: .medium))
                .foregroundStyle(.secondary)
            TextField("Zoek in klembord", text: $model.query)
                .textFieldStyle(.plain)
                .font(.system(size: model.expanded ? 16 : 14))
                .focused($searchFocused)
            Button { model.expanded.toggle() } label: {
                Image(systemName: model.expanded ? "arrow.down.right.and.arrow.up.left" : "arrow.up.left.and.arrow.down.right")
                    .font(.system(size: 11, weight: .semibold))
                    .foregroundStyle(.secondary)
                    .frame(width: 22, height: 22)
                    .background(Circle().fill(Color.primary.opacity(0.07)))
                    .contentShape(Circle())
            }
            .buttonStyle(.plain)
            .help(model.expanded ? "Verkleinen (tab)" : "Vergroten met voorbeeld (tab)")
        }
        .padding(.horizontal, 12)
        .frame(height: model.expanded ? 46 : 38)
    }

    private func list(_ items: [ClipItem]) -> some View {
        ScrollViewReader { proxy in
            ScrollView {
                LazyVStack(spacing: model.expanded ? 2 : 0) {
                    ForEach(Array(items.enumerated()), id: \.element.id) { idx, item in
                        let hovered = hoveredID == item.id
                        ClipRow(item: item, index: idx, selected: idx == model.selection,
                                compact: !model.expanded, copied: model.copiedID == item.id,
                                hovered: hovered, store: store)
                            .id(item.id)
                            .contentShape(Rectangle())
                            // Double click pastes into the focused app; a single click only copies.
                            // Not promoted on copy, so the row stays put under the second click.
                            .onTapGesture(count: 2) { model.onChoose(item, true) }
                            .simultaneousGesture(TapGesture().onEnded { copy(item, at: idx) })
                            // Outside the tap gestures above, so clicking × never also copies.
                            .overlay(alignment: .trailing) {
                                if hovered && model.copiedID != item.id {
                                    deleteButton(item, onAccent: idx == model.selection)
                                }
                            }
                            .onHover { inside in
                                if inside { hoveredID = item.id } else if hoveredID == item.id { hoveredID = nil }
                            }
                            .contextMenu {
                                Button("Plakken") { model.onChoose(item, true) }
                                Button("Kopiëren") { copy(item, at: idx) }
                                Divider()
                                Button("Verwijderen") { model.delete(item) }
                                Button("Alles wissen…") { model.confirmingClear = true }
                            }
                    }
                }
                .padding(5)
            }
            .scrollIndicators(model.expanded ? .automatic : .never)
            .onChange(of: model.selection) {
                guard items.indices.contains(model.selection) else { return }
                proxy.scrollTo(items[model.selection].id)
            }
            .onChange(of: model.focusToken) {
                if let first = items.first { proxy.scrollTo(first.id, anchor: .top) }
            }
        }
    }

    private func copy(_ item: ClipItem, at idx: Int) {
        model.selection = idx
        store.copyToPasteboard(item, promote: false)
        model.copiedID = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) {
            if model.copiedID == item.id { model.copiedID = nil }
        }
    }

    private func deleteButton(_ item: ClipItem, onAccent: Bool) -> some View {
        Button { model.delete(item) } label: {
            Image(systemName: "xmark")
                .font(.system(size: model.expanded ? 9.5 : 8.5, weight: .bold))
                .foregroundStyle(onAccent ? Color.white : Color.secondary)
                .frame(width: model.expanded ? 20 : 16, height: model.expanded ? 20 : 16)
                .background(Circle().fill(onAccent ? Color.white.opacity(0.22) : Color.primary.opacity(0.1)))
                .contentShape(Circle())
        }
        .buttonStyle(.plain)
        .help("Verwijderen (⌘⌫)")
        .padding(.trailing, 8)
    }

    @ViewBuilder private var banner: some View {
        if model.confirmingClear {
            BannerBar {
                Text("Alle \(store.items.count) items wissen?")
                Spacer(minLength: 8)
                Button("Annuleer") { model.confirmingClear = false }
                    .buttonStyle(.plain)
                    .foregroundStyle(.secondary)
                Button("Wis alles") { model.clearAll() }
                    .buttonStyle(.plain)
                    .foregroundStyle(.red)
                    .fontWeight(.semibold)
            }
        } else if store.lastDeleted != nil {
            BannerBar {
                Image(systemName: "trash").foregroundStyle(.secondary)
                Text("Verwijderd")
                Spacer(minLength: 8)
                Button { model.undoDelete() } label: {
                    HStack(spacing: 4) {
                        Text("Ongedaan maken")
                        Text("⌘Z").foregroundStyle(.secondary)
                    }
                }
                .buttonStyle(.plain)
                .foregroundStyle(Color.accentColor)
                .fontWeight(.medium)
            }
        }
    }

    private var emptyState: some View {
        VStack(spacing: 6) {
            Image(systemName: model.query.isEmpty ? "clipboard" : "magnifyingglass")
                .font(.system(size: 22, weight: .light))
                .foregroundStyle(.tertiary)
            Text(model.query.isEmpty ? "Nog niks gekopieerd" : "Geen resultaten")
                .font(.system(size: 12, weight: .medium))
                .foregroundStyle(.secondary)
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }

    private var footer: some View {
        HStack(spacing: 14) {
            Text("\(store.items.count) items")
                .foregroundStyle(.tertiary)
            Spacer()
            KeyHint(keys: "↩", label: "Plakken")
            KeyHint(keys: "⇧↩", label: "Alleen kopiëren")
            KeyHint(keys: "⌘⌫", label: "Verwijder")
            KeyHint(keys: "esc", label: "Sluit")
        }
        .font(.system(size: 11))
        .padding(.horizontal, 14)
        .frame(height: 32)
    }
}

