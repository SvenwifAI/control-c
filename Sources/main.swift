// MARK: - Window & hotkey

final class ClipPanel: NSPanel {
    var keyHandler: ((NSEvent) -> Bool)?

    init(size: CGSize) {
        super.init(contentRect: NSRect(origin: .zero, size: size),
                   styleMask: [.borderless, .nonactivatingPanel, .fullSizeContentView],
                   backing: .buffered, defer: false)
        isFloatingPanel = true
        level = .floating
        collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient, .ignoresCycle]
        backgroundColor = .clear
        isOpaque = false
        hasShadow = false // the glass draws its own
        hidesOnDeactivate = false
        animationBehavior = .none
    }

    override var canBecomeKey: Bool { true }

    override func sendEvent(_ event: NSEvent) {
        if event.type == .keyDown, keyHandler?(event) == true { return }
        super.sendEvent(event)
    }
}

final class HotKey {
    private var ref: EventHotKeyRef?
    private var handler: EventHandlerRef?
    private let action: () -> Void

    init(action: @escaping () -> Void) {
        self.action = action
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, _, userData in
            Unmanaged<HotKey>.fromOpaque(userData!).takeUnretainedValue().action()
            return noErr
        }, 1, &spec, Unmanaged.passUnretained(self).toOpaque(), &handler)
    }

    /// Replaces the current shortcut; false when another app already owns this combination.
    @discardableResult
    func register(_ shortcut: Shortcut) -> Bool {
        unregister()
        let id = EventHotKeyID(signature: OSType(0x434C_4950), id: 1) // 'CLIP'
        return RegisterEventHotKey(UInt32(shortcut.keyCode), UInt32(shortcut.carbonModifiers), id,
                                   GetApplicationEventTarget(), 0, &ref) == noErr
    }

    func unregister() {
        if let ref { UnregisterEventHotKey(ref) }
        ref = nil
    }
}

// MARK: - App

final class AppDelegate: NSObject, NSApplicationDelegate, NSWindowDelegate, NSMenuDelegate {
    let store = ClipStore()
    lazy var model = PickerModel(store: store)
    let settings = Settings.shared
    lazy var settingsWindow = SettingsWindowController { [weak self] in self?.clearHistory() }
    let openItem = NSMenuItem(title: "Open klembord", action: #selector(openFromMenu), keyEquivalent: "")
    var panel: ClipPanel!
    var hotKey: HotKey?
    var statusItem: NSStatusItem!
    let loginItem = NSMenuItem(title: "Start bij inloggen", action: #selector(toggleLogin), keyEquivalent: "")
    let pasteItem = NSMenuItem(title: "Automatisch plakken inschakelen…", action: #selector(requestAccessibility), keyEquivalent: "")

    func applicationDidFinishLaunching(_ notification: Notification) {
        store.start()

        panel = ClipPanel(size: CGSize(width: 340, height: 300))
        panel.delegate = self
        panel.contentView = NSHostingView(rootView: PickerView(model: model, store: store))
        panel.keyHandler = { [weak self] in self?.handleKey($0) ?? false }
        model.onChoose = { [weak self] item, paste in self?.choose(item, paste: paste) }
        model.onResize = { [weak self] in self?.layoutPanel() }
        model.onOpenSettings = { [weak self] in self?.openSettings() }

        hotKey = HotKey { [weak self] in self?.toggle() }
        registerShortcut()
        settings.onShortcutChange = { [weak self] in
            if self?.settings.isRecording == false { self?.registerShortcut() }
        }
        settings.onRecordingChange = { [weak self] recording in
            if recording { self?.hotKey?.unregister() } else { self?.registerShortcut() }
        }
        settings.onLimitsChange = { [weak self] in self?.store.applyLimits() }
        setupStatusItem()

        #if SCREENSHOT_TEST
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { self.show() }
        #endif
        #if SETTINGS_TEST
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { self.openSettings() }
        #endif

        if !AXIsProcessTrusted(), !UserDefaults.standard.bool(forKey: "askedAccessibility") {
            UserDefaults.standard.set(true, forKey: "askedAccessibility")
            requestAccessibility()
        }
    }

    func registerShortcut() {
        settings.shortcutTaken = !(hotKey?.register(settings.shortcut) ?? true)
    }

    @objc func openSettings() {
        hide()
        settingsWindow.show()
    }

    // MARK: Panel

    func toggle() { panel.isVisible ? hide() : show() }

    func show() {
        model.query = ""
        model.kindFilter = nil
        model.selection = 0
        anchor = Self.textCaretRect() ?? NSRect(origin: NSEvent.mouseLocation, size: .zero)
        userMoved = false
        layoutPanel()
        panel.makeKeyAndOrderFront(nil)
        model.focusToken += 1
    }

    /// What the panel hangs off: the text caret, or the mouse pointer. Cocoa screen coordinates.
    private var anchor = NSRect.zero
    /// Set once the user drags the panel; resizing then keeps its top-left corner where they put it.
    private var userMoved = false
    private var isLayingOut = false

    func windowDidMove(_ notification: Notification) {
        if !isLayingOut { userMoved = true }
    }

    private var panelSize: CGSize {
        let m = PickerView.margin * 2
        let top = PickerView.searchHeight + 8
        if model.expanded { return CGSize(width: 740 + m, height: top + 420 + m) }
        // Seven rows, plus half of the eighth when there is more: a visual hint that the list scrolls.
        let count = store.items.count
        let rows = CGFloat(min(max(count, 3), 7)) + (count > 7 ? 0.5 : 0)
        return CGSize(width: 360 + m, height: top + 36 + rows * 28 + 8 + m)
    }

    /// Places the panel just below the anchor, or above it when there is no room, inside the visible screen.
    func layoutPanel() {
        let size = panelSize
        let screen = NSScreen.screens.first { NSMouseInRect(anchor.origin, $0.frame, false) } ?? NSScreen.main
        guard let vf = screen?.visibleFrame else { return }
        var x = anchor.minX - 10 - PickerView.margin
        var y = anchor.minY - 6 + PickerView.margin - size.height
        if y < vf.minY { y = anchor.maxY + 6 }
        if userMoved {
            x = panel.frame.minX
            y = panel.frame.maxY - size.height
        }
        x = min(max(x, vf.minX + 8), vf.maxX - size.width - 8)
        y = min(max(y, vf.minY + 8), vf.maxY - size.height - 8)
        isLayingOut = true
        panel.setFrame(NSRect(x: x, y: y, width: size.width, height: size.height), display: true)
        isLayingOut = false
    }

    /// Bounds of the insertion point in the focused text field of the frontmost app, via Accessibility.
    static func textCaretRect() -> NSRect? {
        guard AXIsProcessTrusted() else { return nil }
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.05) // never let a slow app delay the popup
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        let element = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.05)
        var range: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &range) == .success,
              let range else { return nil }
        var boundsValue: CFTypeRef?
        guard AXUIElementCopyParameterizedAttributeValue(element, kAXBoundsForRangeParameterizedAttribute as CFString,
                                                         range, &boundsValue) == .success,
              let boundsValue, CFGetTypeID(boundsValue) == AXValueGetTypeID() else { return nil }
        var rect = CGRect.zero
        guard AXValueGetValue(boundsValue as! AXValue, .cgRect, &rect),
              rect.origin != .zero, rect.height > 0, rect.height < 200 else { return nil }
        // AX uses top-left origin on the primary screen; Cocoa uses bottom-left.
        let primaryHeight = NSScreen.screens.first?.frame.height ?? 0
        return NSRect(x: rect.minX, y: primaryHeight - rect.maxY, width: rect.width, height: rect.height)
    }

    func hide() {
        panel.orderOut(nil)
        model.confirmingClear = false
        store.finalizeDelete()
    }

    func windowDidResignKey(_ notification: Notification) { hide() }

    func handleKey(_ e: NSEvent) -> Bool {
        let cmd = e.modifierFlags.contains(.command)
        switch Int(e.keyCode) {
        case kVK_Escape:
            if model.confirmingClear { model.confirmingClear = false } else { hide() }
        case kVK_ANSI_Comma where cmd:
            openSettings()
        case kVK_ANSI_Z where cmd:
            model.undoDelete()
        case kVK_UpArrow:
            model.move(-1)
        case kVK_DownArrow:
            model.move(1)
        case kVK_LeftArrow where cmd:
            model.stepKindFilter(-1)
        case kVK_RightArrow where cmd:
            model.stepKindFilter(1)
        case kVK_Tab:
            model.expanded.toggle()
        case kVK_Return, kVK_ANSI_KeypadEnter:
            if let item = model.selected { choose(item, paste: !e.modifierFlags.contains(.shift)) }
        case kVK_Delete where cmd && e.modifierFlags.contains(.shift):
            if !store.items.isEmpty { model.confirmingClear = true }
        case kVK_Delete where cmd:
            if let item = model.selected { model.delete(item) }
        default:
            guard cmd, let n = Int(e.charactersIgnoringModifiers ?? ""), (1...9).contains(n) else { return false }
            let items = model.filtered
            if items.count >= n { choose(items[n - 1], paste: true) }
        }
        return true
    }

    func choose(_ item: ClipItem, paste: Bool) {
        store.copyToPasteboard(item)
        hide()
        // The panel never activates this app, so the previous app is still frontmost and receives ⌘V.
        guard paste, AXIsProcessTrusted() else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
        }
    }

    // MARK: Menu bar

    func setupStatusItem() {
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
        statusItem.button?.image = NSImage(systemSymbolName: "list.clipboard", accessibilityDescription: "Control+C")

        let menu = NSMenu()
        menu.delegate = self
        menu.addItem(openItem)
        menu.addItem(withTitle: "Instellingen…", action: #selector(openSettings), keyEquivalent: ",")
        menu.addItem(.separator())
        menu.addItem(loginItem)
        menu.addItem(pasteItem)
        menu.addItem(withTitle: "Geschiedenis wissen", action: #selector(clearHistory), keyEquivalent: "")
        menu.addItem(.separator())
        menu.addItem(withTitle: "Stop Control+C", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q")
        menu.items.forEach { if $0.action != #selector(NSApplication.terminate(_:)) { $0.target = self } }
        statusItem.menu = menu
    }

    func menuNeedsUpdate(_ menu: NSMenu) {
        openItem.title = "Open klembord   \(settings.shortcut.display)"
        loginItem.state = SMAppService.mainApp.status == .enabled ? .on : .off
        pasteItem.isHidden = AXIsProcessTrusted()
    }

    @objc func openFromMenu() { DispatchQueue.main.async { self.show() } }

    @objc func clearHistory() {
        let alert = NSAlert()
        alert.messageText = "Hele klembordgeschiedenis wissen?"
        alert.informativeText = "Alle \(store.items.count) items worden verwijderd. Dit kan niet ongedaan worden gemaakt."
        alert.addButton(withTitle: "Wis alles").hasDestructiveAction = true
        alert.addButton(withTitle: "Annuleer")
        NSApp.activate()
        if alert.runModal() == .alertFirstButtonReturn { model.clearAll() }
    }

    @objc func toggleLogin() {
        let service = SMAppService.mainApp
        do {
            if service.status == .enabled { try service.unregister() } else { try service.register() }
        } catch {
            NSLog("Control+C login item: \(error)")
        }
    }

    @objc func requestAccessibility() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }
}

let app = NSApplication.shared
let delegate = AppDelegate()
app.delegate = delegate
app.setActivationPolicy(.accessory)
app.run()
