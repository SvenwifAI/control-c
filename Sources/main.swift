        }
    }

    private var iconBorder: some View {
        RoundedRectangle(cornerRadius: compact ? 4.5 : 7, style: .continuous)
            .strokeBorder(selected ? Color.white.opacity(0.6) : Color.primary.opacity(0.15), lineWidth: 0.5)
    }
}

