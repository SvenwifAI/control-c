struct ClipRow: View {
    let item: ClipItem
    let index: Int
    let selected: Bool
    let compact: Bool
    let copied: Bool
    let hovered: Bool
    let store: ClipStore

    private var iconSize: CGFloat { compact ? 18 : 28 }

    var body: some View {
        HStack(spacing: compact ? 8 : 10) {
            thumbnail
            VStack(alignment: .leading, spacing: 1) {
                Text(item.oneLine)
                    .font(.system(size: 13, weight: compact ? .regular : .medium))
                    .lineLimit(1)
                if !compact {
                    Text([item.appName, relativeTime(item.date)].compactMap { $0 }.joined(separator: " · "))
                        .font(.system(size: 11))
                        .foregroundStyle(selected ? Color.white.opacity(0.75) : Color.secondary)
                        .lineLimit(1)
                }
            }
            Spacer(minLength: 4)
            if copied {
                Label("Gekopieerd", systemImage: "checkmark")
                    .font(.system(size: 11, weight: .medium))
                    .foregroundStyle(selected ? Color.white : Color.secondary)
            } else if hovered {
                Color.clear.frame(width: 20, height: 1) // room for the × the list overlays here
            } else if index < 9 {
                // Styled like a native menu key equivalent.
                Text("⌘\(index + 1)")
                    .font(.system(size: 12))
                    .foregroundStyle(selected ? Color.white.opacity(0.8) : Color.secondary)
            }
        }
        .padding(.horizontal, 8)
        .frame(height: compact ? 26 : 44)
        .foregroundStyle(selected ? Color.white : Color.primary)
        .background(
            RoundedRectangle(cornerRadius: compact ? 6 : 9, style: .continuous)
                .fill(selected ? Color.accentColor : Color.clear)
        )
    }

    @ViewBuilder private var thumbnail: some View {
        if let img = store.image(for: item) {
            Image(nsImage: img)
                .resizable()
                .scaledToFill()
                .frame(width: iconSize, height: iconSize)
                .clipShape(RoundedRectangle(cornerRadius: compact ? 4 : 6, style: .continuous))
        } else if item.isLink {
            symbol("link")
        } else if let icon = store.appIcon(for: item) {
            Image(nsImage: icon).resizable().frame(width: iconSize, height: iconSize)
        } else {
            symbol("text.alignleft")
        }
    }

    private func symbol(_ name: String) -> some View {
        Image(systemName: name)
            .font(.system(size: compact ? 10 : 12, weight: .semibold))
            .frame(width: iconSize, height: iconSize)
            .background(
                RoundedRectangle(cornerRadius: compact ? 4.5 : 7, style: .continuous)
                    .fill(selected ? Color.white.opacity(0.2) : Color.primary.opacity(0.08))
            )
    }
}

struct PreviewPane: View {
    let item: ClipItem?
    let store: ClipStore

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            content.frame(maxWidth: .infinity, maxHeight: .infinity)
            if let item {
                Divider().opacity(0.6)
                VStack(alignment: .leading, spacing: 5) {
                    meta("Bron", item.appName ?? "Onbekend")
                    meta("Gekopieerd", item.date.formatted(date: .abbreviated, time: .shortened))
                    if let t = item.text {
                        let lines = t.split(separator: "\n", omittingEmptySubsequences: false).count
                        meta("Inhoud", "\(t.count) tekens · \(lines) \(lines == 1 ? "regel" : "regels")")
                    } else if let img = store.image(for: item) {
                        meta("Afmetingen", "\(Int(img.size.width)) × \(Int(img.size.height))")
                    }
                }
                .padding(.horizontal, 18)
                .padding(.vertical, 12)
            }
        }
    }

    @ViewBuilder private var content: some View {
        if let item, let img = store.image(for: item) {
            Image(nsImage: img)
                .resizable()
                .scaledToFit()
                .clipShape(RoundedRectangle(cornerRadius: 8, style: .continuous))
                .shadow(color: .black.opacity(0.15), radius: 6, y: 2)
                .padding(20)
        } else if let text = item?.text {
            ScrollView {
                Text(String(text.prefix(8000)))
                    .font(.system(size: 13, design: looksLikeCode(text) ? .monospaced : .default))
                    .lineSpacing(2)
                    .textSelection(.enabled)
                    .frame(maxWidth: .infinity, alignment: .leading)
                    .padding(18)
            }
        } else {
            Color.clear
        }
    }

    private func meta(_ key: String, _ value: String) -> some View {
        HStack(alignment: .firstTextBaseline) {
            Text(key).foregroundStyle(.tertiary).frame(width: 82, alignment: .leading)
            Text(value).foregroundStyle(.secondary).lineLimit(1)
        }
        .font(.system(size: 11.5))
    }

    private func looksLikeCode(_ t: String) -> Bool {
        let markers = ["{", "}", ";", "=>", "func ", "def ", "const ", "import ", "</", "$ "]
        return markers.filter { t.contains($0) }.count >= 2
    }
}

